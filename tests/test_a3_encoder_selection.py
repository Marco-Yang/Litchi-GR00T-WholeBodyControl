"""``deploy.sh --robot a3|a3_ultra --encoder a3-fast|smpl|g1``: runtime-config generator, SMPL stand stub, script plumbing.

Pure plumbing tests (no robot, no simulator).  The ONNX tests need the ``onnx`` package and skip without it; the numerical
check of the stub additionally needs ``onnxruntime``.
"""

from __future__ import annotations

import importlib.util
from pathlib import Path
import subprocess
import sys

import numpy as np
import pytest
import yaml

REPO = Path(__file__).resolve().parents[1]
SCRIPTS = REPO / "gear_sonic_deploy" / "scripts"
BASE_CFG = REPO / "gear_sonic_deploy/src/g1/g1_deploy_onnx_ref/config/a3_runtime_config.yaml"


def _load(name: str):
    path = SCRIPTS / f"{name}.py"
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


cfg_tool = _load("a3_make_runtime_cfg")


# ---------------------------------------------------------------------------------------------- runtime config
def _base() -> dict:
    return yaml.safe_load(BASE_CFG.read_text(encoding="utf-8"))


@pytest.mark.parametrize("name,source", [("a3-fast", "a3_fast"), ("a3_fast", "a3_fast"), ("a3fast", "a3_fast"), ("g1", "g1")])
def test_joint_space_encoders_only_select_the_source(name: str, source: str) -> None:
    base = _base()
    out = cfg_tool.build(base, name, None, "localhost", 5561, "pose")
    assert out["teleop"]["default_source"] == source
    # nothing else of the packaged config changes (the SMPL block keeps its packaged, disabled-by-need values)
    assert out["onnx"] == base["onnx"]
    assert out["smpl_zmq"] == base["smpl_zmq"]


def test_smpl_encoder_sets_model_and_stream() -> None:
    out = cfg_tool.build(_base(), "smpl", "/models/model_step_9_smpl.onnx", "10.0.0.7", 5561, "pose")
    assert out["teleop"]["default_source"] == "smpl"
    assert out["onnx"]["smpl_model_path"] == "/models/model_step_9_smpl.onnx"
    assert "smpl_rknn_model_path" not in out["onnx"]
    assert out["smpl_zmq"]["enabled"] is True
    assert (out["smpl_zmq"]["host"], out["smpl_zmq"]["port"], out["smpl_zmq"]["topic"]) == ("10.0.0.7", 5561, "pose")
    # the g1 / a3_fast policies stay available (the SMPL stream can drop out and the deploy falls back to the stand reference)
    assert out["onnx"]["model_path"] == _base()["onnx"]["model_path"]
    assert out["onnx"]["a3_fast_model_path"] == _base()["onnx"]["a3_fast_model_path"]


def test_smpl_rknn_model_goes_to_the_rknn_key() -> None:
    out = cfg_tool.build(_base(), "smpl", "/models/model_smpl.rknn", "localhost", 5561, "pose")
    assert out["onnx"]["smpl_rknn_model_path"] == "/models/model_smpl.rknn"
    assert out["onnx"].get("smpl_model_path") == _base()["onnx"].get("smpl_model_path")


def test_smpl_encoder_without_a_model_is_an_error() -> None:
    with pytest.raises(SystemExit):
        cfg_tool.build(_base(), "smpl", None, "localhost", 5561, "pose")


def test_generated_file_round_trips(tmp_path: Path) -> None:
    out = tmp_path / "generated.yaml"
    result = subprocess.run(
        [sys.executable, str(SCRIPTS / "a3_make_runtime_cfg.py"), "--base", str(BASE_CFG), "--out", str(out),
         "--encoder", "smpl", "--smpl-model", "/m/smpl.onnx", "--smpl-zmq-host", "robot-pc"],
        capture_output=True, text=True, check=False,
    )
    assert result.returncode == 0, result.stderr
    text = out.read_text(encoding="utf-8")
    assert text.startswith("# GENERATED by a3_make_runtime_cfg.py")
    cfg = yaml.safe_load(text)
    assert cfg["teleop"]["default_source"] == "smpl" and cfg["smpl_zmq"]["host"] == "robot-pc"


# ---------------------------------------------------------------------------------------------- SMPL stand stub
onnx = pytest.importorskip("onnx")
smpl_tool = _load("a3_smpl_onnx_tool")


def _tiny_a3_fast(path: Path) -> None:
    """A stand-in for the monolithic a3_fast export: obs_dict[1,1570] -> action[1,29] (one linear layer + tanh)."""
    from onnx import TensorProto, helper, numpy_helper

    rng = np.random.default_rng(1)
    w = numpy_helper.from_array(rng.normal(scale=0.05, size=(1570, 29)).astype(np.float32), "w")
    b = numpy_helper.from_array(rng.normal(scale=0.1, size=(29,)).astype(np.float32), "b")
    nodes = [
        helper.make_node("MatMul", ["obs_dict", "w"], ["h"]),
        helper.make_node("Add", ["h", "b"], ["z"]),
        helper.make_node("Tanh", ["z"], ["action"]),
    ]
    graph = helper.make_graph(
        nodes, "tiny_a3_fast",
        [helper.make_tensor_value_info("obs_dict", TensorProto.FLOAT, [1, 1570])],
        [helper.make_tensor_value_info("action", TensorProto.FLOAT, [1, 29])],
        initializer=[w, b],
    )
    model = helper.make_model(graph, opset_imports=[helper.make_opsetid("", 13)])
    model.ir_version = 7
    onnx.save(model, str(path))


def test_stub_has_the_smpl_policy_interface(tmp_path: Path) -> None:
    base, stub = tmp_path / "a3_fast.onnx", tmp_path / "smpl_stub.onnx"
    _tiny_a3_fast(base)
    assert smpl_tool.check(base), "an a3_fast export must be rejected as an SMPL policy"
    smpl_tool.make_stand_stub(stub, base)
    assert smpl_tool.check(stub) == []


def test_stub_is_the_a3_fast_policy_on_the_stand_tokenizer(tmp_path: Path) -> None:
    ort = pytest.importorskip("onnxruntime")
    from gear_sonic.utils.teleop.a3.reference_buffer import build_default_stand_tokenizer_slice

    base, stub = tmp_path / "a3_fast.onnx", tmp_path / "smpl_stub.onnx"
    _tiny_a3_fast(base)
    smpl_tool.make_stand_stub(stub, base)
    s_stub = ort.InferenceSession(str(stub), providers=["CPUExecutionProvider"])
    s_base = ort.InferenceSession(str(base), providers=["CPUExecutionProvider"])
    stand = build_default_stand_tokenizer_slice().astype(np.float32).reshape(1, 640)
    rng = np.random.default_rng(2)
    obs = rng.normal(size=(1, 1770)).astype(np.float32)
    want = s_base.run(["action"], {"obs_dict": np.concatenate([stand, obs[:, 840:]], axis=1)})[0]
    assert np.array_equal(s_stub.run(["action"], {"obs_dict": obs})[0], want)
    # the SMPL tokenizer (first 840 floats) must not matter, the proprioception history must
    obs2 = obs.copy()
    obs2[:, :840] = rng.normal(size=(1, 840)).astype(np.float32)
    assert np.array_equal(s_stub.run(["action"], {"obs_dict": obs2})[0], want)
    obs3 = obs.copy()
    obs3[:, 900] += 1.0
    assert not np.array_equal(s_stub.run(["action"], {"obs_dict": obs3})[0], want)


def test_check_flags_wrong_action_width(tmp_path: Path) -> None:
    from onnx import TensorProto, helper

    graph = helper.make_graph(
        [helper.make_node("Identity", ["obs_dict"], ["action"])], "bad",
        [helper.make_tensor_value_info("obs_dict", TensorProto.FLOAT, [1, 1770])],
        [helper.make_tensor_value_info("action", TensorProto.FLOAT, [1, 31])],
    )
    model = helper.make_model(graph, opset_imports=[helper.make_opsetid("", 13)])
    model.ir_version = 7
    path = tmp_path / "bad.onnx"
    onnx.save(model, str(path))
    problems = smpl_tool.check(path)
    assert len(problems) == 1 and "[1, 29]" in problems[0]


