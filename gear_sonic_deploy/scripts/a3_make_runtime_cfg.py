#!/usr/bin/env python3
"""Write an A3 runtime config for ``deploy.sh --encoder``.

Takes the packaged ``a3_runtime_config.yaml`` and sets, for the selected TELEOP encoder:

* ``teleop.default_source``                      g1 | smpl | a3_fast   (the C++ also gets ``--teleop-source``)
* for ``smpl``: ``onnx.smpl_model_path`` (``onnx.smpl_rknn_model_path`` for a ``.rknn`` file) and the ``smpl_zmq``
  block (``enabled``, ``host``, ``port``, ``topic``) -- where the SMPL pose stream with A3 wrist angles is published
  (``a3_teleop_retarget_node.py --mode smpl-pose``, default port 5561).

The result is written next to the base config so its relative paths (``models/...``) keep resolving.  Comments of the
base file are not carried over; the output starts with a header saying so.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys

import yaml

ENCODERS = {"a3-fast": "a3_fast", "a3_fast": "a3_fast", "a3fast": "a3_fast", "smpl": "smpl", "g1": "g1"}


def build(base: dict, encoder: str, smpl_model: str | None, host: str, port: int, topic: str) -> dict:
    cfg = dict(base)
    source = ENCODERS[encoder.lower()]
    cfg["teleop"] = {**(cfg.get("teleop") or {}), "default_source": source}
    if source == "smpl":
        if not smpl_model:
            raise SystemExit("--encoder smpl needs --smpl-model")
        onnx = dict(cfg.get("onnx") or {})
        if smpl_model.endswith(".rknn"):
            onnx["smpl_rknn_model_path"] = smpl_model
        else:
            onnx["smpl_model_path"] = smpl_model
        cfg["onnx"] = onnx
        cfg["smpl_zmq"] = {**(cfg.get("smpl_zmq") or {}), "enabled": True, "host": host, "port": port, "topic": topic}
    return cfg


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--base", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--encoder", required=True, choices=sorted(ENCODERS))
    ap.add_argument("--smpl-model", default=None, help="absolute path of the monolithic SMPL ONNX (or .rknn)")
    ap.add_argument("--smpl-zmq-host", default="localhost")
    ap.add_argument("--smpl-zmq-port", type=int, default=5561)
    ap.add_argument("--smpl-zmq-topic", default="pose")
    args = ap.parse_args()

    base = yaml.safe_load(args.base.read_text(encoding="utf-8")) or {}
    cfg = build(base, args.encoder, args.smpl_model, args.smpl_zmq_host, args.smpl_zmq_port, args.smpl_zmq_topic)
    header = (
        f"# GENERATED by a3_make_runtime_cfg.py from {args.base.name} for --encoder {args.encoder}.\n"
        "# Comments of the base file are not carried over; edit the base file, not this one.\n"
    )
    args.out.write_text(header + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True), encoding="utf-8")
    print(f"[a3] runtime config for --encoder {args.encoder}: {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
